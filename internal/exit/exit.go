// Package exit — коды выхода figma-kai.
//
// Это контракт с вызывающим: команду зовёт агент и по коду решает, что делать
// дальше, не разбирая текст. Точная причина всегда лежит в JSON-конверте.
//
// Коды 2 и 3 совпадают по смыслу с sec, ci-kai и yk-kai — во всей семье CLI
// они значат одно и то же.
package exit

const (
	// OK — операция выполнена.
	OK = 0

	// NotApplied — Figma ответила, но результата нет: картинку узла она не
	// отрендерила (в ответе null вместо ссылки). Инструмент исправен, узел —
	// нет: скрытый слой, пустая группа, слишком большой фрейм.
	NotApplied = 1

	// Tool — ошибка инструмента или аргументов: нет токена, Figma отвергла
	// авторизацию, неизвестная команда, ссылка без node-id.
	Tool = 2

	// NotFound — файла или узла с таким id нет (или нет к нему доступа).
	NotFound = 3

	// Timeout — Figma не ответила за отведённое время. Ничего не изменилось,
	// команды только читают — звать ещё раз.
	Timeout = 4
)
